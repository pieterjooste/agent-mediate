/** Wrap counterparty-supplied `idempotencyKey`, `nonce`, and `signatureInput` strings on verified `/signatures` responses (`SEC-10`, `SEC-1`, `SA2-OPS-M2`). */
export function markSignatures(res: unknown, ownAgentDid: string): unknown {
  const out = structuredClone(res) as {
    signatures?: Array<{ redacted?: boolean; agentId?: string | null; proof?: Record<string, unknown> | null }>;
  } | null;
  for (const entry of out?.signatures ?? []) {
    if (!entry || typeof entry !== "object" || entry.redacted === true || entry.agentId === ownAgentDid) continue;
    if (entry.proof && typeof entry.proof === "object") {
      wrapAt(entry, "/proof/idempotencyKey", "counterparty");
      wrapAt(entry, "/proof/nonce", "counterparty");
      wrapAt(entry, "/proof/signatureInput", "counterparty");
    }
  }
  return out;
}

