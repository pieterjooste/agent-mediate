const FORBIDDEN_PROTO_KEYS = new Set(["__proto__", "constructor", "prototype"]);

function isPlainRecord(value: unknown): value is Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return false;
  const proto = Object.getPrototypeOf(value);
  return proto === Object.prototype || proto === null;
}

/** Replace the string at an RFC 6901 pointer with an untrusted wrapper. Missing paths and non-strings are left alone. */
function wrapAt(root: unknown, pointer: string, authoredBy: string): void {
  const keys = pointer.split("/").slice(1).map((k) => k.replace(/~1/g, "/").replace(/~0/g, "~"));
  for (const k of keys) {
    if (FORBIDDEN_PROTO_KEYS.has(k)) return;
  }
  let parent: unknown = root;
  for (const k of keys.slice(0, -1)) {
    if (parent === null || typeof parent !== "object") return;
    if (Array.isArray(parent)) {
      const idx = Number(k);
      if (!Number.isInteger(idx) || idx < 0 || idx >= parent.length) return;
      parent = parent[idx];
    } else if (Object.prototype.hasOwnProperty.call(parent, k)) {
      parent = (parent as Record<string, unknown>)[k];
    } else {
      return;
    }
  }
  const last = keys[keys.length - 1];
  if (last === undefined || parent === null || typeof parent !== "object") return;
  if (Array.isArray(parent)) {
    const idx = Number(last);
    if (!Number.isInteger(idx) || idx < 0 || idx >= parent.length || typeof parent[idx] !== "string") return;
    parent[idx] = { untrusted: true, authoredBy, text: parent[idx] };
    return;
  }
  if (!Object.prototype.hasOwnProperty.call(parent, last)) return;
  const current = (parent as Record<string, unknown>)[last];
  if (typeof current !== "string") return;
  Object.defineProperty(parent, last, {
    value: { untrusted: true, authoredBy, text: current },
    enumerable: true,
    writable: true,
    configurable: true,
  });
}

function wrapFields(root: unknown, fields: Field[] | undefined): void {
  for (const f of fields ?? []) wrapAt(root, f.path, f.authoredBy);
}

function sha256Canonical(value: unknown): string {
  return createHash("sha256").update(canonicalJson(value)).digest("hex");
}

function ownRecordEntry(obj: unknown, key: string): unknown {
  if (!isPlainRecord(obj) || FORBIDDEN_PROTO_KEYS.has(key)) return undefined;
  return Object.prototype.hasOwnProperty.call(obj, key) ? obj[key] : undefined;
}

function readMandateRange(mandateBounds: unknown, issueId: string): { min: number; max: number } | null {
  const entry = ownRecordEntry(mandateBounds, issueId);
  if (!isPlainRecord(entry)) return null;
  if (typeof entry.min !== "number" || typeof entry.max !== "number" || !Number.isFinite(entry.min) || !Number.isFinite(entry.max)) {
    return null;
  }
  return { min: entry.min, max: entry.max };
}

function valueWithinRange(value: unknown, range: { min: number; max: number } | null): boolean | null {
  if (range === null || typeof value !== "number" || !Number.isFinite(value)) return null;
  return value >= range.min - 1e-9 && value <= range.max + 1e-9;
}

export interface ProposalDetailsItem {
  id: string;
  value?: number;
  currentValue?: number | null;
  proposedValue?: number;
  label: unknown;
  unit: unknown;
  obligor: string | null;
  yourMandateRange?: { min: number; max: number } | null;
  withinYourMandate?: boolean | null;
}

export interface ProposalDetails {
  kind: "PLATFORM_PROPOSAL" | "PARETO_IMPROVEMENT" | "SETTLEMENT_EXECUTION" | "SIGNED_SETTLEMENT_OUTCOME";
  disputeId: string | null;
  status?: string;
  yourRole?: string;
  round?: number;
  proposalId?: string;
  method?: string;
  terms?: Record<string, number>;
  currentSettlementTerms?: Record<string, number> | null;
  proposedTerms?: Record<string, number>;
  termsHash: string;
  items: ProposalDetailsItem[];
  withinYourMandate?: boolean | null;
  meetsYourWalkaway?: boolean | null;
  mandateWideningRequired?: boolean;
  roundDeadline?: number | null;
  wallClockDeadline?: number | null;
  executionDeadline?: number | null;
  obligors?: string[];
  counterpartyProof?: unknown;
  groundingRule: string;
}

function buildItemsFromTerms(
  issuesRaw: unknown,
  terms: Record<string, number>,
  mandateBounds: unknown,
  currentTerms?: Record<string, number> | null,
): ProposalDetailsItem[] {
  const issues = Array.isArray(issuesRaw) ? issuesRaw : [];
  const seen = new Set<string>();
  const items: ProposalDetailsItem[] = [];
  for (const raw of issues) {
    if (!isPlainRecord(raw) || typeof raw.id !== "string") continue;
    const id = raw.id;
    seen.add(id);
    const val = ownRecordEntry(terms, id);
    const numVal = typeof val === "number" && Number.isFinite(val) ? val : undefined;
    const range = readMandateRange(mandateBounds, id);
    const base: ProposalDetailsItem = {
      id,
      label: raw.label ?? null,
      unit: raw.unit ?? null,
      obligor: typeof raw.obligor === "string" ? raw.obligor : null,
      ...(mandateBounds !== undefined ? { yourMandateRange: range, withinYourMandate: valueWithinRange(numVal, range) } : {}),
    };
    if (currentTerms !== undefined) {
      const cur = ownRecordEntry(currentTerms, id);
      base.currentValue = typeof cur === "number" && Number.isFinite(cur) ? cur : null;
      if (numVal !== undefined) base.proposedValue = numVal;
    } else if (numVal !== undefined) {
      base.value = numVal;
    }
    items.push(base);
  }
  for (const id of Object.keys(terms)) {
    if (seen.has(id) || FORBIDDEN_PROTO_KEYS.has(id)) continue;
    const val = terms[id];
    if (typeof val !== "number" || !Number.isFinite(val)) continue;
    const range = readMandateRange(mandateBounds, id);
    const base: ProposalDetailsItem = {
      id,
      label: null,
      unit: null,
      obligor: null,
      ...(mandateBounds !== undefined ? { yourMandateRange: range, withinYourMandate: valueWithinRange(val, range) } : {}),
    };
    if (currentTerms !== undefined) {
      const cur = ownRecordEntry(currentTerms, id);
      base.currentValue = typeof cur === "number" && Number.isFinite(cur) ? cur : null;
      base.proposedValue = val;
    } else {
      base.value = val;
    }
    items.push(base);
  }
  return items;
}

/**
 * Build a deterministic, verbatim `PROPOSAL_DETAILS` confirmation object from an already-wrapped
 * party view (`BARGAINING` open proposal, `EXECUTION_PENDING` Pareto improvement, or settlement execution).
 * Preserves `{ untrusted: true, authoredBy, text }` wrappers on issue labels/units and counterparty proof refs.
 */
export function buildProposalDetails(view: unknown): ProposalDetails | null {
  if (!isPlainRecord(view)) return null;
  const disputeIdVal = typeof view.disputeId === "string" ? view.disputeId : null;
  const statusVal = typeof view.status === "string" ? view.status : undefined;
  const roleVal = typeof view.you === "string" ? view.you : undefined;
  const mandateBounds = isPlainRecord(view.yourMandate) ? view.yourMandate.bounds : undefined;

  // 1. Open platform proposal during BARGAINING
  const bargaining = isPlainRecord(view.bargaining) ? view.bargaining : null;
  const openProposal = bargaining && isPlainRecord(bargaining.openProposal) ? bargaining.openProposal : null;
  if (statusVal === "BARGAINING" && openProposal && isPlainRecord(openProposal.terms)) {
    const terms = openProposal.terms as Record<string, number>;
    const withinRaw =
      typeof view.proposalWithinYourMandate === "boolean"
        ? view.proposalWithinYourMandate
        : typeof bargaining?.proposalWithinYourMandate === "boolean"
          ? bargaining.proposalWithinYourMandate
          : null;
    const meetsRaw =
      typeof view.proposalMeetsYourWalkaway === "boolean"
        ? view.proposalMeetsYourWalkaway
        : typeof bargaining?.proposalMeetsYourWalkaway === "boolean"
          ? bargaining.proposalMeetsYourWalkaway
          : null;
    return {
      kind: "PLATFORM_PROPOSAL",
      disputeId: disputeIdVal,
      status: statusVal,
      ...(roleVal ? { yourRole: roleVal } : {}),
      ...(typeof bargaining?.round === "number" ? { round: bargaining.round } : {}),
      ...(typeof openProposal.id === "string" ? { proposalId: openProposal.id } : {}),
      terms,
      termsHash: sha256Canonical(terms),
      items: buildItemsFromTerms(view.issues, terms, mandateBounds),
      withinYourMandate: withinRaw,
      meetsYourWalkaway: meetsRaw,
      mandateWideningRequired: withinRaw === false,
      roundDeadline: typeof bargaining?.roundDeadline === "number" ? bargaining.roundDeadline : null,
      wallClockDeadline: typeof bargaining?.wallClockDeadline === "number" ? bargaining.wallClockDeadline : null,
      groundingRule: PROPOSAL_GROUNDING_RULE,
    };
  }

  // 2. Open post-settlement Pareto improvement during EXECUTION_PENDING
  const execution = isPlainRecord(view.execution) ? view.execution : null;
  const improvement = execution && isPlainRecord(execution.improvement) ? execution.improvement : null;
  const outcome = isPlainRecord(view.outcome) ? view.outcome : null;
  if (
    statusVal === "EXECUTION_PENDING" &&
    improvement &&
    improvement.status === "OPEN" &&
    isPlainRecord(improvement.terms)
  ) {
    const proposedTerms = improvement.terms as Record<string, number>;
    const currentTerms =
      outcome && outcome.kind === "SETTLED" && isPlainRecord(outcome.terms) ? (outcome.terms as Record<string, number>) : null;
    const items = buildItemsFromTerms(view.issues, proposedTerms, mandateBounds, currentTerms);
    const withinChecks = items.map((it) => it.withinYourMandate).filter((v): v is boolean => typeof v === "boolean");
    const withinAll = withinChecks.length > 0 ? withinChecks.every(Boolean) : null;
    return {
      kind: "PARETO_IMPROVEMENT",
      disputeId: disputeIdVal,
      status: statusVal,
      ...(roleVal ? { yourRole: roleVal } : {}),
      currentSettlementTerms: currentTerms,
      proposedTerms,
      termsHash: sha256Canonical(proposedTerms),
      items,
      withinYourMandate: withinAll,
      executionDeadline: typeof execution?.deadline === "number" ? execution.deadline : null,
      groundingRule: PROPOSAL_GROUNDING_RULE,
    };
  }

  // 3. Settled terms awaiting execution / confirmation during EXECUTION_PENDING
  if (statusVal === "EXECUTION_PENDING" && outcome && outcome.kind === "SETTLED" && isPlainRecord(outcome.terms)) {
    const terms = outcome.terms as Record<string, number>;
    const cp = roleVal === "claimant" ? "respondent" : roleVal === "respondent" ? "claimant" : null;
    const proofs = execution && isPlainRecord(execution.proofs) ? execution.proofs : null;
    const counterpartyProof = cp && proofs ? (ownRecordEntry(proofs, cp) ?? null) : null;
    return {
      kind: "SETTLEMENT_EXECUTION",
      disputeId: disputeIdVal,
      status: statusVal,
      ...(roleVal ? { yourRole: roleVal } : {}),
      ...(typeof outcome.method === "string" ? { method: outcome.method } : {}),
      terms,
      termsHash: sha256Canonical(terms),
      items: buildItemsFromTerms(view.issues, terms, undefined),
      obligors: Array.isArray(execution?.obligors) ? execution.obligors.filter((x): x is string => typeof x === "string") : [],
      counterpartyProof,
      executionDeadline: typeof execution?.deadline === "number" ? execution.deadline : null,
      groundingRule: PROPOSAL_GROUNDING_RULE,
    };
  }

  return null;
}

/** Build `PROPOSAL_DETAILS` from an already-wrapped verified settlement outcome document. */
function buildOutcomeProposalDetails(res: unknown): ProposalDetails | null {
  if (!isPlainRecord(res) || !isPlainRecord(res.document)) return null;
  const doc = res.document;
  if (doc.type !== "agent-mediate/settlement-instruction/v1" || !isPlainRecord(doc.terms)) return null;
  const terms = doc.terms as Record<string, number>;
  return {
    kind: "SIGNED_SETTLEMENT_OUTCOME",
    disputeId: typeof doc.disputeId === "string" ? doc.disputeId : null,
    ...(typeof doc.method === "string" ? { method: doc.method } : {}),
    terms,
    termsHash: sha256Canonical(terms),
    items: buildItemsFromTerms(doc.issues, terms, undefined),
    obligors: Array.isArray(doc.obligors) ? doc.obligors.filter((x): x is string => typeof x === "string") : [],
    executionDeadline: typeof doc.executionDeadline === "number" ? doc.executionDeadline : null,
    groundingRule: PROPOSAL_GROUNDING_RULE,
  };
}

/** A dispute response (view + advisory) with every untrusted string wrapped and structured `PROPOSAL_DETAILS` attached when applicable. */
export function markDisputeResponse(res: unknown): unknown {
  const out = structuredClone(res) as Record<string, unknown> | null;
  if (!out || typeof out !== "object") return out;
  const view = out.view as { untrusted?: { fields?: Field[] } } | undefined;
  if (view?.untrusted) wrapFields(view, view.untrusted.fields);
  const adv = out.advisory;
  if (isPlainRecord(adv)) {
    const ai = "ai-from-party-text";
    wrapAt(adv, "/evidenceSummary", ai);
    if (Array.isArray(adv.candidateDisputedFacts)) {
      adv.candidateDisputedFacts.forEach((_: unknown, i: number) => wrapAt(adv, `/candidateDisputedFacts/${i}`, ai));
    }
    if (Array.isArray(adv.candidateAgreedFacts)) {
      adv.candidateAgreedFacts.forEach((fact: unknown, i: number) => {
        wrapAt(adv, `/candidateAgreedFacts/${i}/statement`, ai);
        const evIds = isPlainRecord(fact) && Array.isArray(fact.evidenceIds) ? fact.evidenceIds : [];
        evIds.forEach((_: unknown, j: number) => wrapAt(adv, `/candidateAgreedFacts/${i}/evidenceIds/${j}`, ai));
      });
    }
    if (Array.isArray(adv.suggestedIssues)) {
      adv.suggestedIssues.forEach((_: unknown, i: number) => {
        for (const k of ["rationale", "issue/id", "issue/label", "issue/unit"]) wrapAt(adv, `/suggestedIssues/${i}/${k}`, ai);
      });
    }
  }
  const proposalDetails = buildProposalDetails(out.view);
  if (proposalDetails) {
    out.PROPOSAL_DETAILS = proposalDetails;
  }
  return out;
}

/** Events (data paths in event.untrusted) and list rows (paths in row.untrusted) with untrusted strings wrapped. */
function markEvents(res: unknown): unknown {
  const out = structuredClone(res) as { events?: Array<{ data: unknown; untrusted?: Field[] }> } | null;
  for (const e of out?.events ?? []) wrapFields(e.data, e.untrusted);
  return out;
}

/**
 * A verified outcome document (CR2-7): issue labels and units were written by the claimant (or suggested by the AI)
 * and are signed into the document verbatim, so they are wrapped as untrusted like everywhere else.
 * Attaches structured `PROPOSAL_DETAILS` on settlement instructions so principals can verify exact signed terms.
 */
export function markOutcome(res: unknown): unknown {
  const out = structuredClone(res) as (Record<string, unknown> & { document?: { issues?: unknown[] } }) | null;
  (out?.document?.issues ?? []).forEach((_: unknown, i: number) => {
    wrapAt(out?.document, `/issues/${i}/label`, "claimant-or-ai");
    wrapAt(out?.document, `/issues/${i}/unit`, "claimant-or-ai");
  });
  if (out) {
    const proposalDetails = buildOutcomeProposalDetails(out);
    if (proposalDetails) out.PROPOSAL_DETAILS = proposalDetails;
  }
  return out;
}

function markList(res: unknown): unknown {
  const out = structuredClone(res) as { disputes?: Array<{ untrusted?: Field[] }> } | null;
  for (const d of out?.disputes ?? []) wrapFields(d, d.untrusted);
  return out;
}

/** Wrap counterparty-supplied `idempotencyKey`, `nonce`, and `signatureInput` strings on verified `/signatures` responses (`SEC-10`, `SEC-1`, `SA2-OPS-M2`). */
export function markSignatures(res: unknown, ownAgentDid: string): unknown {
  const out = structuredClone(res) as {
    signatures?: Array<{ redacted?: boolean; agentId?: string | null; proof?: Record<string, unknown> | null }>;
  } | null;
  for (const entry of out?.signatures ?? []) {
    if (!entry || typeof entry !== "object" || entry.redacted === true || entry.agentId === ownAgentDid) continue;
    if (entry.proof && typeof entry.proof === "object") {
      wrapAt(entry, "/proof/idempotencyKey", "counterparty");
      wrapAt(entry, "/proof/nonce", "counterparty");
      wrapAt(entry, "/proof/signatureInput", "counterparty");
    }
  }
  return out;
}

