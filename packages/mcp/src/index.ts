function assertAllowedKeys(obj: unknown, allowed: Set<string>, label: string): asserts obj is Record<string, unknown> {
  if (!isPlainRecord(obj)) {
    throw new Error(`${label} must be a JSON object`);
  }
  for (const k of Object.getOwnPropertyNames(obj)) {
    if (FORBIDDEN_PROTO_KEYS.has(k)) {
      throw new Error(`forbidden property "${k}" in ${label}`);
    }
    if (!allowed.has(k)) {
      throw new Error(`unexpected property "${k}" in ${label}`);
    }
  }
}

const MAX_UNWRAP_DEPTH = 32;

/**
 * Recursively unwrap `{ untrusted: true, authoredBy, text }` wrappers back to raw `text`
 * so tool outputs from `sign_dispute_clause` / `verify_dispute_clause` can be passed into
 * `verify_dispute_clause` or `file_dispute` without invalidating JCS signatures (`FS-H5`).
 * Rejects any own `__proto__`, `constructor`, or `prototype` key (`SEC-3`) and caps nesting depth (`SA2-DOC-I1`).
 */
export function unwrapUntrusted<T>(value: T, depth = 0): T {
  if (depth > MAX_UNWRAP_DEPTH) {
    throw new Error(`input exceeds maximum nesting depth (${MAX_UNWRAP_DEPTH})`);
  }
  if (value === null || typeof value !== "object") return value;
  if (Array.isArray(value)) return value.map((item) => unwrapUntrusted(item, depth + 1)) as unknown as T;
  if (!isPlainRecord(value)) return value;
  const ownNames = Object.getOwnPropertyNames(value);
  for (const k of ownNames) {
    if (FORBIDDEN_PROTO_KEYS.has(k)) {
      throw new Error(`forbidden property "${k}" in input`);
    }
  }
  if (
    value.untrusted === true &&
    typeof value.text === "string" &&
    ownNames.every((k) => k === "untrusted" || k === "authoredBy" || k === "text")
  ) {
    return value.text as unknown as T;
  }
  const out: Record<string, unknown> = {};
  for (const k of ownNames) {
    if (!Object.prototype.propertyIsEnumerable.call(value, k)) continue;
    Object.defineProperty(out, k, {
      value: unwrapUntrusted(value[k], depth + 1),
      enumerable: true,
      writable: true,
      configurable: true,
    });
  }
  return out as T;
}

function isDisputeClauseRecord(raw: Record<string, unknown>): raw is Record<string, unknown> & DisputeClause {
  return typeof raw.type === "string" || raw.type === undefined;
}

function validateClauseShape(raw: unknown): DisputeClause {
  assertAllowedKeys(raw, CLAUSE_KEYS, "clause");
  if (raw.platform !== undefined) {
    assertAllowedKeys(raw.platform, CLAUSE_PLATFORM_KEYS, "clause.platform");
  }
  if (raw.parties !== undefined) {
    if (!Array.isArray(raw.parties)) throw new Error("clause.parties must be an array");
    raw.parties.forEach((p, idx) => {
      assertAllowedKeys(p, CLAUSE_PARTY_KEYS, `clause.parties[${idx}]`);
      if (p.notice !== undefined) {
        assertAllowedKeys(p.notice, PARTY_CONTACT_KEYS, `clause.parties[${idx}].notice`);
      }
    });
  }
  if (raw.terms !== undefined) {
    assertAllowedKeys(raw.terms, CLAUSE_TERMS_KEYS, "clause.terms");
    if (raw.terms.windows !== undefined) {
      assertAllowedKeys(raw.terms.windows, CLAUSE_WINDOW_KEYS, "clause.terms.windows");
    }
    if (raw.terms.issueTemplates !== undefined) {
      if (!Array.isArray(raw.terms.issueTemplates)) throw new Error("clause.terms.issueTemplates must be an array");
      raw.terms.issueTemplates.forEach((it, idx) => assertAllowedKeys(it, ISSUE_KEYS, `clause.terms.issueTemplates[${idx}]`));
    }
  }
  if (raw.signatures !== undefined) {
    if (!Array.isArray(raw.signatures)) throw new Error("clause.signatures must be an array");
    raw.signatures.forEach((s, idx) => assertAllowedKeys(s, CLAUSE_SIG_KEYS, `clause.signatures[${idx}]`));
  }
  if (!isDisputeClauseRecord(raw)) throw new Error("invalid clause shape");
  return raw;
}

function normalizePartyContact(contact?: PartyContact): Record<string, string> | null {
  if (!contact) return null;
  const out: Record<string, string> = {};
  for (const k of ["webhookUrl", "a2aCardUrl", "didWeb", "email"] as const) {
    if (contact[k] !== undefined) out[k] = contact[k]!;
  }
  return Object.keys(out).length > 0 ? out : null;
}

function markClausePartyInPlace(party: unknown, ownAgentDid: string): void {
  if (!isPlainRecord(party) || party.agentId === ownAgentDid) return;
  for (const k of ["webhookUrl", "a2aCardUrl", "didWeb", "email"]) {
    wrapAt(party, `/notice/${k}`, "counterparty");
  }
}

export function markClause(clause: unknown, ownAgentDid: string, wrapTemplates = true): unknown {
  const out = structuredClone(clause) as { parties?: unknown[]; terms?: { issueTemplates?: unknown[] } } | null;
  if (Array.isArray(out?.parties)) {
    for (const p of out.parties) markClausePartyInPlace(p, ownAgentDid);
  }
  if (wrapTemplates && Array.isArray(out?.terms?.issueTemplates)) {
    out.terms.issueTemplates.forEach((_: unknown, i: number) => {
      wrapAt(out, `/terms/issueTemplates/${i}/label`, "counterparty");
      wrapAt(out, `/terms/issueTemplates/${i}/unit`, "counterparty");
    });
  }
  return out;
}

function markVerifiedClause(verdict: unknown, ownAgentDid: string): unknown {
  const out = structuredClone(verdict) as {
    ok?: boolean;
    reason?: unknown;
    parties?: unknown[];
    claimantParty?: unknown;
    respondentParty?: unknown;
  } | null;
  if (out?.ok === true) {
    if (Array.isArray(out.parties)) {
      for (const p of out.parties) markClausePartyInPlace(p, ownAgentDid);
    }
    if (out.claimantParty) markClausePartyInPlace(out.claimantParty, ownAgentDid);
    if (out.respondentParty) markClausePartyInPlace(out.respondentParty, ownAgentDid);
  } else if (out?.ok === false && typeof out.reason === "string") {
    wrapAt(out, "/reason", "counterparty-or-validator");
  }
  return out;
}

const SAFE_PAYMENT_STRING_KEYS = new Set(["scheme", "network", "amount", "asset", "payTo"]);

function markPaymentRequired(challenge: unknown, depth = 0): unknown {
  if (depth > MAX_UNWRAP_DEPTH || challenge === null || typeof challenge !== "object") return challenge;
  if (Array.isArray(challenge)) return challenge.map((item) => markPaymentRequired(item, depth + 1));
  if (!isPlainRecord(challenge)) return challenge;
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(challenge)) {
    if (FORBIDDEN_PROTO_KEYS.has(k)) continue;
    if (typeof v === "string" && !SAFE_PAYMENT_STRING_KEYS.has(k)) {
      out[k] = { untrusted: true, authoredBy: "platform-or-facilitator", text: v };
    } else {
      out[k] = markPaymentRequired(v, depth + 1);
    }
  }
  return out;
}

/** Validate principal-signed mandates loaded from `AGENT_MEDIATE_MANDATE_FILE` (`FS-M15`). */
export function validateConfiguredMandates(mandates: Mandate[], agentDid: string, now = Date.now()): void {
  if (!Array.isArray(mandates) || mandates.length === 0) {
    throw new Error("configured mandates list must be non-empty");
  }
  for (const m of mandates) {
    if (!m || typeof m !== "object" || !isDidKey(m.principalId) || !isDidKey(m.agentId)) {
      throw new Error(`mandate ${String((m as { id?: unknown })?.id)} has an invalid principalId or agentId`);
    }
    if (!Number.isSafeInteger(m.expiresAt) || m.expiresAt <= 0) {
      throw new Error(`mandate ${m.id} has an invalid expiresAt timestamp`);
    }
    if (!verifyMandateSignature(m)) {
      throw new Error(`mandate ${m.id} has an invalid principal Ed25519 signature`);
    }
  }
  const forAgent = mandates.filter((m) => m.agentId === agentDid);
  if (forAgent.length === 0) {
    throw new Error(`no mandate is issued to this agent (${agentDid})`);
  }
  if (!forAgent.some((m) => m.expiresAt > now)) {
    throw new Error(`all configured mandates for this agent (${agentDid}) have expired`);
  }
}

/** Pick an active, signature-verified principal mandate for this agent, contract and counterparty (security review H2, `FS-M15`). */
export function pickMandate(
  mandates: Mandate[],
  agentId: string,
  ctx: { contractHash: string; counterpartyId: string },
  now?: number,
): Mandate | undefined {
  const matches = mandates.filter(
    (m) =>
      m.agentId === agentId &&
      (now === undefined || m.expiresAt > now) &&
      verifyMandateSignature(m) &&
      (m.scope?.contractHash === undefined || m.scope.contractHash === ctx.contractHash) &&
      (m.scope?.counterpartyId === undefined || m.scope.counterpartyId === ctx.counterpartyId),
  );
  matches.sort((a, b) => (b.issuedAt ?? 0) - (a.issuedAt ?? 0));
  return matches[0];
}

function ok(value: unknown): ToolResult {
  return { content: [{ type: "text", text: JSON.stringify(value) }] };
}

function fail(e: unknown): ToolResult {
  if (e instanceof PaymentRequiredError) {
    return {
      isError: true,
      content: [
        {
          type: "text",
          text: JSON.stringify({
            code: e.code,
            detail: "A fee is due. Configure AGENT_MEDIATE_PAYER_KEY to pay automatically.",
            ...(e.hint ? { hint: { untrusted: true, authoredBy: "platform-or-facilitator", text: e.hint } } : {}),
            paymentRequired: markPaymentRequired(e.paymentRequired),
          }),
        },
      ],
    };
  }
  if (e instanceof PaymentPolicyError) {
    return { isError: true, content: [{ type: "text", text: JSON.stringify({ code: "PAYMENT_REFUSED_BY_POLICY", detail: e.message }) }] };
  }
  if (e instanceof AgentMediateError) {
    return {
      isError: true,
      content: [
        {
          type: "text",
          text: JSON.stringify({
            status: e.status,
            code: e.code,
            detail: e.message,
            ...(e.hint ? { hint: { untrusted: true, authoredBy: "platform-or-facilitator", text: e.hint } } : {}),
            ...(e.docs ? { docs: { untrusted: true, authoredBy: "platform-or-facilitator", text: e.docs } } : {}),
            // CR-SDK-M1: retrying the SAME tool call with the same arguments reuses this key automatically; it is
            // surfaced so a model never "fixes" a lost response by forcing a fresh key (which could pay twice).
            ...(e.idempotencyKey ? { idempotencyKey: e.idempotencyKey } : {}),
            ...(e.paymentSent ? { paymentSent: true } : {}),
          }),
        },
      ],
    };
  }
  return { isError: true, content: [{ type: "text", text: JSON.stringify({ code: "CLIENT_ERROR", detail: (e as Error).message }) }] };
}

const run = (fn: () => Promise<unknown>) => async (): Promise<ToolResult> => {
  try {
    return ok(await fn());
  } catch (e) {
    return fail(e);
  }
};

/** Like run, for tools returning a dispute response: untrusted strings are wrapped (security review M12). */
const runMarked = (fn: () => Promise<unknown>) => run(async () => markDisputeResponse(await fn()));

function normalizeUrlForHash(raw: unknown): unknown {
  if (typeof raw !== "string") return raw;
  const trimmed = raw.trim();
  if (!trimmed) return undefined;
  try {
    const u = new URL(trimmed);
    const s = u.toString();
    return u.pathname === "/" && !u.search && !u.hash && !trimmed.slice(u.origin.length).includes("/") ? s.replace(/\/$/, "") : s.replace(/\/+$/, "");
  } catch {
    return trimmed.replace(/\/+$/, "");
  }
}

/**
 * CR-SDK-M1 & SA2-MCP-L1: a stable Idempotency-Key for a PAID tool call (`file_dispute`), derived from normalized
 * (agent, tool, unwrapped arguments, optional baseUrl). A model that retries the same call after a lost response
 * (even if `clause` was wrapped vs unwrapped or a URL carried trailing slashes) replays the original request and
 * its payment instead of signing a second authorisation. An explicit `idempotencyKey` argument overrides it.
 */
export function paidToolIdempotencyKey(
  did: string,
  tool: string,
  args: Record<string, unknown>,
  baseUrl?: string,
): string {
  const { idempotencyKey: explicit, ...rest } = args;
  if (typeof explicit === "string" && explicit.length > 0) return explicit;
  const unwrapped = unwrapUntrusted(rest);
  if (isPlainRecord(unwrapped)) {
    if ("webhookUrl" in unwrapped) unwrapped.webhookUrl = normalizeUrlForHash(unwrapped.webhookUrl);
    if (isPlainRecord(unwrapped.respondentContact)) {
      if ("webhookUrl" in unwrapped.respondentContact) {
        unwrapped.respondentContact.webhookUrl = normalizeUrlForHash(unwrapped.respondentContact.webhookUrl);
      }
      if ("a2aCardUrl" in unwrapped.respondentContact) {
        unwrapped.respondentContact.a2aCardUrl = normalizeUrlForHash(unwrapped.respondentContact.a2aCardUrl);
      }
    }
    if (isPlainRecord(unwrapped.clause) && isPlainRecord(unwrapped.clause.platform) && "baseUrl" in unwrapped.clause.platform) {
      unwrapped.clause.platform.baseUrl = normalizeUrlForHash(unwrapped.clause.platform.baseUrl);
    }
  }
  const normBase = baseUrl !== undefined ? normalizeUrlForHash(baseUrl) : undefined;
  const payload: Record<string, unknown> = {
    did,
    tool,
    args: unwrapped,
    ...(normBase !== undefined ? { baseUrl: normBase } : {}),
  };
  const material = canonicalJson(JSON.parse(JSON.stringify(payload)) as Record<string, unknown>);
  return `mcp-${tool}-${createHash("sha256").update(material).digest("hex").slice(0, 40)}`;
}

