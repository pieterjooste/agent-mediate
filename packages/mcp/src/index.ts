  const validateUpgradedMandate = (rawMandate: Record<string, unknown>): Mandate => {
    const clean = unwrapUntrusted(rawMandate);
    if (!isMandateRecord(clean) || clean.agentId !== client.did) {
      throw new Error(`upgraded mandate must be issued to this agent (${client.did})`);
    }
    if (!Number.isSafeInteger(clean.expiresAt) || clean.expiresAt <= nowFn()) {
      throw new Error("upgraded mandate has expired");
    }
    if (!verifyMandateSignature(clean)) {
      throw new Error("upgraded mandate has an invalid principal Ed25519 signature");
    }
    if (mandates && !mandates.some((cm) => cm.agentId === client.did && cm.principalId === clean.principalId)) {
      throw new Error("upgraded mandate principalId does not match any configured principal in AGENT_MEDIATE_MANDATE_FILE");
    }
    return clean;
  };

