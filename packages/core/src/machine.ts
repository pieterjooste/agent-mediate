/** Per issue, a new offer may not move against the counterparty. */
function requireNoRetraction(issues: Issue[], actor: Party, previous: Package | null, next: Package): void {
  if (previous === null) return;
  for (const issue of issues) {
    const before = claimantShare(issue, previous[issue.id]!);
    const after = claimantShare(issue, next[issue.id]!);
    const retracts = actor === "claimant" ? after > before + EPS : after < before - EPS;
    if (retracts) fail("RETRACTION", `offer on ${issue.id} is worse for the counterparty than your previous offer`);
  }
}

function requireStatus(s: DisputeState, status: Status): void {
  if (s.status !== status) fail("INVALID_STATE", `dispute is ${s.status}, expected ${status}`);
}

function requireParty(s: DisputeState, actor: string): PartyState {
  if (actor !== "claimant" && actor !== "respondent") fail("NOT_AUTHORIZED", "actor must be claimant or respondent");
  const party = s.parties[actor];
  if (party === null) fail("NOT_AUTHORIZED", "respondent has not joined");
  return party;
}

function requireNow(now: number): void {
  if (!Number.isSafeInteger(now) || now <= 0) fail("INVALID_INPUT", "now must be a positive safe integer timestamp");
}

function emit(tx: Tx, type: string, visibility: Visibility, data: Record<string, unknown>): void {
  const e = buildEvent(tx.state.audit.salt, tx.state.audit, type, tx.now, visibility, structuredClone(data));
  tx.state.audit.seq = e.seq;
  tx.state.audit.head = e.hash;
  tx.events.push(e);
}

function toError(e: unknown): ApplyResult {
  if (e instanceof DomainError) return { ok: false, error: { code: e.code, message: e.message } };
  throw e;
}
