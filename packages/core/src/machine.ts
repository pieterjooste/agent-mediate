function handle(tx: Tx, cmd: Exclude<Command, { type: "TICK" }>): void {
  const s = tx.state;
  switch (cmd.type) {
    case "JOIN": {
      requireStatus(s, "AWAITING_RESPONDENT");
      if (cmd.actor !== "respondent" || cmd.respondentId !== s.respondentId) {
        fail("NOT_AUTHORIZED", "only the named respondent can join");
      }
      validateMandateShape(cmd.mandate, s.respondentId, tx.now);
      requireMandateScope(cmd.mandate, { contractHash: s.contractHash, counterpartyId: s.parties.claimant.id });
      // CR2-9: the respondent may lengthen any window the claimant chose (effective = the longer of the two).
      const raised: Partial<Record<(typeof JOIN_WINDOW_KEYS)[number], number>> = {};
      for (const key of JOIN_WINDOW_KEYS) {
        const v = cmd.windows?.[key];
        if (v === undefined) continue;
        const { min, max } = CONFIG_LIMITS[key];
        if (!Number.isInteger(v) || v < min || v > max) fail("INVALID_INPUT", `windows.${key} must be an integer from ${min} to ${max}`);
        if (v > s.config[key]) raised[key] = v;
      }
      Object.assign(s.config, raised);
      if (s.config.bargainingWallClockMs < s.config.roundTimeoutMs) {
        s.config.bargainingWallClockMs = s.config.roundTimeoutMs;
        raised.bargainingWallClockMs = s.config.roundTimeoutMs;
      }
      s.parties.respondent = {
        id: s.respondentId,
        mandate: structuredClone(cmd.mandate),
        feePaid: cmd.feePaid ?? false,
        determinationConsent: cmd.mandate.determinationConsent === true,
        discloseGapOnFailure: cmd.discloseGapOnFailure === true,
      };
      s.status = "EVIDENCE";
      s.stageDeadline = tx.now + s.config.stageTimeoutMs;
      emit(tx, "RESPONDENT_JOINED", "both", {
        respondentId: s.respondentId,
        determinationEnabled: s.parties.claimant.determinationConsent && s.parties.respondent.determinationConsent,
        gapDisclosureEnabled: s.parties.claimant.discloseGapOnFailure && s.parties.respondent.discloseGapOnFailure,
        evidenceDeadline: s.stageDeadline,
        ...(Object.keys(raised).length ? { windowsRaised: raised } : {}),
      });
      emit(tx, "MANDATE_REGISTERED", "internal", { party: "respondent", mandate: s.parties.respondent.mandate });
      return;
    }

    case "SUBMIT_EVIDENCE": {
      requireStatus(s, "EVIDENCE");
      requireParty(s, cmd.actor);
      if (s.evidenceClosed[cmd.actor]) fail("INVALID_STATE", "you have already closed evidence");
      if (!Array.isArray(cmd.items) || cmd.items.length < 1 || cmd.items.length > MAX_EVIDENCE_PER_CALL) {
        fail("INVALID_INPUT", `between 1 and ${MAX_EVIDENCE_PER_CALL} evidence items per submission`);
      }
      const mine = s.evidence.filter((e) => e.submittedBy === cmd.actor).length;
      if (mine + cmd.items.length > MAX_EVIDENCE_PER_PARTY) {
        fail("INVALID_INPUT", `at most ${MAX_EVIDENCE_PER_PARTY} evidence items per party`);
      }
      const ids = new Set(s.evidence.map((e) => e.id));
      for (const item of cmd.items) {
        validateEvidenceItem(item);
        if (ids.has(item.id)) fail("INVALID_INPUT", `duplicate evidence id "${item.id}"`);
        ids.add(item.id);
      }
      const added = cmd.items.map((i) => ({
        id: i.id,
        submittedBy: cmd.actor,
        kind: i.kind,
        sha256: i.sha256,
        description: i.description,
        at: tx.now,
      }));
      s.evidence.push(...added);
      emit(tx, "EVIDENCE_SUBMITTED", "both", { party: cmd.actor, items: added });
      return;
    }

    case "CLOSE_EVIDENCE": {
      requireStatus(s, "EVIDENCE");
      requireParty(s, cmd.actor);
      if (s.evidenceClosed[cmd.actor]) fail("ALREADY_SUBMITTED", "evidence already closed");
      s.evidenceClosed[cmd.actor] = true;
      emit(tx, "EVIDENCE_CLOSED_BY", "both", { party: cmd.actor });
      if (s.evidenceClosed.claimant && s.evidenceClosed.respondent) {
        emit(tx, "EVIDENCE_CLOSED", "both", { byDeadline: false });
        openIssueConfirmation(tx);
      }
      return;
    }

    case "PROPOSE_ISSUES": {
      requireStatus(s, "ISSUE_CONFIRMATION");
      if (cmd.actor !== "system") fail("NOT_AUTHORIZED", "issues are proposed by the platform");
      const neg = s.issueNegotiation;
      if (neg.proposed !== null) fail("INVALID_STATE", "an issue list is already awaiting confirmation");
      if (neg.proposalCount >= s.config.maxIssueProposals) fail("INVALID_STATE", "issue proposal limit reached");
      validateIssues(cmd.issues);
      const issues = structuredClone(cmd.issues);
      neg.proposed = issues;
      neg.proposedHash = issuesHash(issues);
      neg.confirmed = { claimant: false, respondent: false };
      neg.proposalCount += 1;
      if (neg.requestedSuggestedIds?.length) {
        neg.priorAdoptedSuggestedIds = [...(neg.priorAdoptedSuggestedIds ?? []), [...neg.requestedSuggestedIds]];
      }
      delete neg.requestedSuggestedIds;
      s.stageDeadline = tx.now + s.config.stageTimeoutMs;
      emit(tx, "ISSUES_PROPOSED", "both", {
        issues,
        issuesHash: neg.proposedHash,
        proposalNumber: neg.proposalCount,
        deadline: s.stageDeadline,
      });
      return;
    }

    case "CONFIRM_ISSUES": {
      requireStatus(s, "ISSUE_CONFIRMATION");
      const party = requireParty(s, cmd.actor);
      const neg = s.issueNegotiation;
      if (neg.proposed === null) fail("INVALID_STATE", "no issue list is awaiting confirmation");
      if (cmd.issuesHash !== neg.proposedHash) fail("HASH_MISMATCH", "issuesHash does not match the proposed issue list");
      if (neg.confirmed[cmd.actor]) fail("ALREADY_SUBMITTED", "issues already confirmed");
      if (cmd.mandate !== undefined) {
        validateMandateShape(cmd.mandate, party.id, tx.now);
        // A replacement must come from the same principal: otherwise an agent could swap in a mandate it
        // signed itself and exceed its principal's authority (security review H2).
        if (cmd.mandate.principalId !== party.mandate.principalId) fail("MANDATE_VIOLATION", "a replacement mandate must be issued by the same principal");
        // CR2-11: and must be newer, so an older (possibly wider) mandate can't be swapped back in.
        if (typeof cmd.mandate.issuedAt !== "number" || cmd.mandate.issuedAt <= (party.mandate.issuedAt ?? Number.NEGATIVE_INFINITY)) {
          fail("MANDATE_VIOLATION", "a replacement mandate must carry an issuedAt later than the current mandate's");
        }
        requireMandateScope(cmd.mandate, { contractHash: s.contractHash, counterpartyId: s.parties[other(cmd.actor)]!.id });
        party.mandate = structuredClone(cmd.mandate);
        party.determinationConsent = party.mandate.determinationConsent === true;
      }
      // CR3-SVC-M1 (D129): always emit MANDATE_REGISTERED at issue confirmation whether replaced or reused so event count is invariant.
      emit(tx, "MANDATE_REGISTERED", "internal", {
        party: cmd.actor,
        mandate: party.mandate,
        replaced: cmd.mandate !== undefined,
      });
      requireActiveMandate(party.mandate, tx.now);
      requireMandateCovers(party.mandate, neg.proposed);
      // MECH-5: the mandate must outlive bargaining (plus determination when this mandate consents to it),
      // even if the counterparty confirms right at the end of the current issue-confirmation window.
      const bargainingStartBound = neg.confirmed[other(cmd.actor)] ? tx.now : (s.stageDeadline ?? tx.now);
      const requiredHorizon = s.config.bargainingWallClockMs + (party.determinationConsent ? s.config.determinationTimeoutMs : 0);
      if (party.mandate.expiresAt <= bargainingStartBound + requiredHorizon) {
        fail("MANDATE_EXPIRED", "mandate expires before bargaining (and determination, if enabled) could complete");
      }
      neg.confirmed[cmd.actor] = true;
      emit(tx, "ISSUES_CONFIRMED_BY", "both", { party: cmd.actor, issuesHash: neg.proposedHash });
      if (neg.confirmed.claimant && neg.confirmed.respondent) {
        // M-10: After an outage deadline extension, the first confirmer's mandate may have expired or fallen
        // below the bargaining/determination horizon before the second party confirmed. Never enter BARGAINING
        // with an expired or under-horizon mandate; reset the stale party's confirmation so they can re-confirm
        // with a renewed mandate (or let ISSUE_CONFIRMATION expire cleanly as ISSUES_NOT_AGREED).
        const otherActor = other(cmd.actor);
        const otherParty = s.parties[otherActor]!;
        const otherRequiredHorizon =
          s.config.bargainingWallClockMs + (otherParty.determinationConsent ? s.config.determinationTimeoutMs : 0);
        if (otherParty.mandate.expiresAt <= tx.now || otherParty.mandate.expiresAt <= tx.now + otherRequiredHorizon) {
          neg.confirmed[otherActor] = false;
          return;
        }
        delete neg.priorAdoptedSuggestedIds;
        s.issues = structuredClone(neg.proposed);
        startBargaining(tx);
      }
      return;
    }

    case "REJECT_ISSUES": {
      requireStatus(s, "ISSUE_CONFIRMATION");
      requireParty(s, cmd.actor);
      const neg = s.issueNegotiation;
      if (neg.proposed === null) fail("INVALID_STATE", "no issue list is awaiting confirmation");
      if (cmd.issuesHash !== neg.proposedHash) fail("HASH_MISMATCH", "issuesHash does not match the proposed issue list");
      let adopted: string[] | undefined;
      if (cmd.adoptSuggestedIds !== undefined) {
        adopted = validateAdoptSuggestedIds(cmd.adoptSuggestedIds);
        if (neg.proposalCount >= s.config.maxIssueProposals) {
          fail("INVALID_STATE", "issue proposal limit reached; no further proposals can adopt suggested issues");
        }
        neg.requestedSuggestedIds = adopted;
      } else {
        delete neg.requestedSuggestedIds;
        delete neg.priorAdoptedSuggestedIds;
      }
      emit(tx, "ISSUES_REJECTED", "both", {
        party: cmd.actor,
        issuesHash: neg.proposedHash,
        proposalNumber: neg.proposalCount,
        ...(adopted ? { adoptSuggestedIds: adopted } : {}),
      });
      neg.proposed = null;
      neg.proposedHash = null;
      neg.confirmed = { claimant: false, respondent: false };
      if (neg.proposalCount >= s.config.maxIssueProposals) {
        unresolved(tx, "ISSUES_NOT_AGREED");
      } else {
        s.stageDeadline = tx.now + s.config.stageTimeoutMs;
      }
      return;
    }

    case "UPDATE_MANDATE": {
      if (s.status !== "BARGAINING" && s.status !== "DETERMINATION") {
        fail("INVALID_STATE", `dispute is ${s.status}, expected BARGAINING or DETERMINATION`);
      }
      const party = requireParty(s, cmd.actor);
      if ((party.mandateUpdates ?? 0) >= MAX_MANDATE_UPDATES) {
        fail("MANDATE_VIOLATION", `at most ${MAX_MANDATE_UPDATES} mandate updates per party`);
      }
      validateMandateShape(cmd.mandate, party.id, tx.now);
      if (cmd.mandate.principalId !== party.mandate.principalId) {
        fail("MANDATE_VIOLATION", "a replacement mandate must be issued by the same principal");
      }
      if (typeof cmd.mandate.issuedAt !== "number" || cmd.mandate.issuedAt <= (party.mandate.issuedAt ?? Number.NEGATIVE_INFINITY)) {
        fail("MANDATE_VIOLATION", "a replacement mandate must carry an issuedAt later than the current mandate's");
      }
      requireMandateScope(cmd.mandate, { contractHash: s.contractHash, counterpartyId: s.parties[other(cmd.actor)]!.id });
      requireActiveMandate(cmd.mandate, tx.now);
      const issues = s.issues!;
      requireMandateCovers(cmd.mandate, issues);
      requireMandateMonotonicExpansion(issues, party.mandate, party.determinationConsent, cmd.mandate);
      const declared = s.bargaining?.private[cmd.actor];
      if (declared?.limits && !withinMandateLimits(issues, cmd.mandate, declared.limits)) {
        fail("MANDATE_VIOLATION", "updated mandate bounds must cover your declared private.limits");
      }
      // CR3-CORE-L1: compute the unshifted stage horizon from the current stage's startedAt so pre-bargaining
      // or prior-stage extendDeadlines shifts never over-subtract from wallClockDeadline / determination.deadline.
      if (s.status === "BARGAINING") {
        const requiredHorizon =
          s.bargaining!.startedAt +
          s.config.bargainingWallClockMs +
          (cmd.mandate.determinationConsent === true ? s.config.determinationTimeoutMs : 0);
        if (cmd.mandate.expiresAt <= requiredHorizon) {
          fail("MANDATE_EXPIRED", "mandate expires before bargaining (and determination, if enabled) could complete");
        }
      } else {
        const detHorizon =
          s.determination!.startedAt !== undefined
            ? s.determination!.startedAt + s.config.determinationTimeoutMs
            : s.determination!.deadline - (s.outageExtensionMs ?? 0);
        if (cmd.mandate.expiresAt <= detHorizon) {
          fail("MANDATE_EXPIRED", "mandate expires before determination could complete");
        }
      }
      for (const existingPkg of [
        declared?.walkaway ?? null,
        s.bargaining?.lastOffer[cmd.actor] ?? null,
        s.bargaining?.submissions[cmd.actor]?.offer ?? null,
      ]) {
        if (existingPkg !== null && !withinMandate(issues, cmd.mandate, existingPkg)) {
          fail("MANDATE_VIOLATION", "updated mandate bounds must cover your standing bargaining offer and declared walkaway");
        }
      }
      if (cmd.mandate.determinationConsent === true) {
        for (const existingOffer of [
          s.bargaining?.lastOffer[cmd.actor] ?? null,
          s.bargaining?.submissions[cmd.actor]?.offer ?? null,
          s.determination?.finalOffers[cmd.actor] ?? null,
        ]) {
          if (existingOffer !== null && !withinDeterminationMandate(issues, cmd.mandate, existingOffer)) {
            fail("MANDATE_VIOLATION", "determinationBounds must cover your standing bargaining offer");
          }
        }
      }
      party.mandate = structuredClone(cmd.mandate);
      party.determinationConsent = cmd.mandate.determinationConsent === true;
      party.mandateUpdates = (party.mandateUpdates ?? 0) + 1;
      // CR3-SVC-M1 (D129): emit zero domain events on UPDATE_MANDATE so audit-chain sequence numbers stay
      // count-invariant; the active mandate and update counter are committed inside ROUND_SUBMISSION / FINAL_OFFER.
      return;
    }

    case "SUBMIT_ROUND": {
      requireStatus(s, "BARGAINING");
      const party = requireParty(s, cmd.actor);
      const b = s.bargaining!;
      const issues = s.issues!;
      if (cmd.round !== b.round) fail("WRONG_ROUND", `round ${b.round} is open`);
      if (b.submissions[cmd.actor] !== null) fail("ALREADY_SUBMITTED", `already submitted for round ${b.round}`);
      requireActiveMandate(party.mandate, tx.now);
      validatePackage(issues, cmd.offer, "offer");
      if (!withinMandate(issues, party.mandate, cmd.offer)) fail("MANDATE_VIOLATION", "offer exceeds your mandate");
      if (
        s.parties.claimant.determinationConsent &&
        s.parties.respondent!.determinationConsent &&
        !withinDeterminationMandate(issues, party.mandate, cmd.offer)
      ) {
        fail("MANDATE_VIOLATION", "offer exceeds your determinationBounds while binding determination is enabled");
      }
      requireNoRetraction(issues, cmd.actor, b.lastOffer[cmd.actor], cmd.offer);

      // Private inputs are fixed by the first offer. Changing them later would let a party probe the
      // counterparty through the recomputed proposal (security review M13). Resending the same values is fine.
      const declared = b.private[cmd.actor];
      if (cmd.private !== undefined) {
        validatePrivate(issues, cmd.private);
        if (!withinMandate(issues, party.mandate, cmd.private.walkaway)) {
          fail("MANDATE_VIOLATION", "private.walkaway exceeds your mandate");
        }
        if (cmd.private.limits && !withinMandateLimits(issues, party.mandate, cmd.private.limits)) {
          fail("MANDATE_VIOLATION", "private.limits exceeds your mandate");
        }
        if (declared !== null && canonicalJson(declared) !== canonicalJson(cmd.private)) {
          fail("INVALID_INPUT", "private inputs are fixed by your first offer and cannot be changed");
        }
      } else if (declared === null) fail("INVALID_INPUT", "private inputs are required with your first offer");

      let response: "accept" | "reject" | null = null;
      if (b.proposal !== null) {
        // Since CR2-2 a proposal is open in every round from proposalFromRound, so not answering means "reject".
        if (cmd.proposalResponse !== undefined && cmd.proposalResponse !== "accept" && cmd.proposalResponse !== "reject") {
          fail("INVALID_INPUT", "proposalResponse must be accept or reject");
        }
        if (cmd.proposalResponse === "accept" && !withinMandate(issues, party.mandate, proposalTermsFor(b.proposal, cmd.actor))) {
          fail("MANDATE_VIOLATION", "accepting this proposal would exceed your mandate");
        }
        response = cmd.proposalResponse ?? "reject";
      } else if (cmd.proposalResponse !== undefined) {
        fail("INVALID_INPUT", "no proposal is open in this round");
      }

      if (cmd.private !== undefined) b.private[cmd.actor] = structuredClone(cmd.private);
      let newlyDeclaredVerification: { declaredCommitment: string; partySalt: string } | undefined;
      if (declared === null && b.private[cmd.actor] !== null) {
        const partySalt = derivePartyInputSalt(s.audit.salt, s.id, cmd.actor);
        const declaredCommitment = computeDeclaredInputCommitment(s.id, cmd.actor, partySalt, b.private[cmd.actor]!);
        s.declaredCommitments = { ...(s.declaredCommitments ?? {}), [cmd.actor]: declaredCommitment };
        newlyDeclaredVerification = { declaredCommitment, partySalt };
      }
      b.submissions[cmd.actor] = { offer: structuredClone(cmd.offer), proposalResponse: response, at: tx.now };
      emit(tx, "SUBMISSION_RECEIVED", cmd.actor, { round: b.round, ...(newlyDeclaredVerification ?? {}) });
      emit(tx, "ROUND_SUBMISSION", "internal", {
        party: cmd.actor,
        round: b.round,
        offer: cmd.offer,
        private: cmd.private ?? null,
        proposalResponse: response,
        mandate: party.mandate,
        mandateUpdates: party.mandateUpdates ?? 0,
        ...(newlyDeclaredVerification ? { declaredCommitment: newlyDeclaredVerification.declaredCommitment } : {}),
      });
      if (b.submissions.claimant !== null && b.submissions.respondent !== null) resolveRound(tx);
      return;
    }

    case "SUBMIT_FINAL_OFFER": {
      requireStatus(s, "DETERMINATION");
      const party = requireParty(s, cmd.actor);
      const a = s.determination!;
      const issues = s.issues!;
      if (a.finalOffers[cmd.actor] !== null) fail("ALREADY_SUBMITTED", "final offer already submitted");
      requireActiveMandate(party.mandate, tx.now);
      validatePackage(issues, cmd.offer, "offer");
      if (!withinDeterminationMandate(issues, party.mandate, cmd.offer)) fail("MANDATE_VIOLATION", "offer exceeds your determination mandate");
      requireNoRetraction(issues, cmd.actor, s.bargaining!.lastOffer[cmd.actor], cmd.offer);
      a.finalOffers[cmd.actor] = structuredClone(cmd.offer);
      emit(tx, "FINAL_OFFER_RECEIVED", cmd.actor, {});
      emit(tx, "FINAL_OFFER", "internal", {
        party: cmd.actor,
        offer: cmd.offer,
        mandate: party.mandate,
        mandateUpdates: party.mandateUpdates ?? 0,
      });
      if (a.finalOffers.claimant !== null && a.finalOffers.respondent !== null && a.reference !== null) resolveDetermination(tx);
      return;
    }

    case "SET_DETERMINATION_REFERENCE": {
      requireStatus(s, "DETERMINATION");
      if (cmd.actor !== "system") fail("NOT_AUTHORIZED", "the determination reference is set by the platform");
      const a = s.determination!;
      if (a.reference !== null) fail("ALREADY_SUBMITTED", "reference already set");
      validatePackage(s.issues!, cmd.terms, "reference");
      a.reference = structuredClone(cmd.terms);
      emit(tx, "DETERMINATION_REFERENCE", "internal", { terms: cmd.terms });
      if (a.finalOffers.claimant !== null && a.finalOffers.respondent !== null) resolveDetermination(tx);
      return;
    }

    case "RESPOND_IMPROVEMENT": {
      requireStatus(s, "EXECUTION_PENDING");
      const party = requireParty(s, cmd.actor);
      const ex = s.execution!;
      const imp = ex.improvement;
      if (!imp || imp.status !== "OPEN") fail("INVALID_STATE", "no post-settlement improvement is open");
      if (imp.responses[cmd.actor] !== null) fail("ALREADY_SUBMITTED", "already responded to post-settlement improvement");
      if (cmd.response !== "accept" && cmd.response !== "decline") fail("INVALID_INPUT", "response must be accept or decline");
      if (cmd.response === "accept") {
        requireActiveMandate(party.mandate, tx.now);
        if (!withinMandate(s.issues!, party.mandate, imp.terms)) {
          fail("MANDATE_VIOLATION", "accepting this improvement would exceed your mandate");
        }
      }
      imp.responses[cmd.actor] = cmd.response;
      emit(tx, "IMPROVEMENT_RESPONSE_RECEIVED", cmd.actor, { response: cmd.response });
      emit(tx, "IMPROVEMENT_RESPONSE", "internal", { party: cmd.actor, response: cmd.response });
      if (cmd.response === "decline") {
        imp.status = "DECLINED";
        emit(tx, "IMPROVEMENT_DECLINED", "both", { declinedBy: cmd.actor });
        return;
      }
      if (imp.responses.claimant === "accept" && imp.responses.respondent === "accept") {
        const issues = s.issues!;
        if (s.parties.claimant.mandate.expiresAt <= tx.now || s.parties.respondent!.mandate.expiresAt <= tx.now) {
          imp.status = "DECLINED";
          emit(tx, "IMPROVEMENT_DECLINED", "both", {});
          return;
        }
        if (!withinMandate(issues, s.parties.claimant.mandate, imp.terms) || !withinMandate(issues, s.parties.respondent!.mandate, imp.terms)) {
          imp.status = "DECLINED";
          emit(tx, "IMPROVEMENT_DECLINED", "both", {});
          return;
        }
        imp.status = "ACCEPTED";
        const obligors = computeObligors(issues, imp.terms);
        const settled = s.outcome;
        if (!settled || settled.kind !== "SETTLED") fail("INVALID_STATE", "dispute is not settled");
        const nextTerms = structuredClone(imp.terms);
        const termsHash = computeTermsHash(nextTerms);
        s.outcome = { ...settled, terms: nextTerms, at: tx.now };
        ex.obligors = obligors;
        if (obligors.length === 0) {
          ex.deadline = tx.now;
          s.status = "HONORED";
        }
        const outcomeHash = computeOutcomeHash(s.outcome, s.status);
        emit(tx, "SETTLEMENT_IMPROVED", "both", {
          terms: nextTerms,
          obligors,
          termsHash,
          outcomeHash,
        });
        if (obligors.length === 0) {
          emit(tx, "HONORED", "both", { noObligations: true, outcomeHash });
        }
      }
      return;
    }

    case "SUBMIT_EXECUTION_PROOF": {
      requireStatus(s, "EXECUTION_PENDING");
      requireParty(s, cmd.actor);
      const ex = s.execution!;
      if (!ex.obligors.includes(cmd.actor)) fail("NOT_AUTHORIZED", "you have no obligations under this settlement");
      if (ex.confirmed[cmd.actor]) fail("INVALID_STATE", "performance already confirmed");
      requireText(cmd.reference, 1, 500, "reference");
      if (ex.improvement?.status === "OPEN") {
        ex.improvement.status = "DECLINED";
        emit(tx, "IMPROVEMENT_DECLINED", "both", { reason: "EXECUTION_STARTED", party: cmd.actor });
      }
      ex.proofs[cmd.actor] = { reference: cmd.reference, at: tx.now };
      emit(tx, "EXECUTION_PROOF_SUBMITTED", "both", { party: cmd.actor, reference: cmd.reference });
      return;
    }

    case "CONFIRM_EXECUTION": {
      requireStatus(s, "EXECUTION_PENDING");
      requireParty(s, cmd.actor);
      const ex = s.execution!;
      const obligor = other(cmd.actor);
      if (!ex.obligors.includes(obligor)) fail("INVALID_STATE", "the counterparty has no obligations to confirm");
      if (ex.confirmed[obligor]) fail("ALREADY_SUBMITTED", "already confirmed");
      if (ex.improvement?.status === "OPEN") {
        ex.improvement.status = "DECLINED";
        emit(tx, "IMPROVEMENT_DECLINED", "both", { reason: "EXECUTION_STARTED", party: cmd.actor });
      }
      ex.confirmed[obligor] = true;
      if (ex.contested) ex.contested[obligor] = null;
      emit(tx, "EXECUTION_CONFIRMED", "both", { obligor, confirmedBy: cmd.actor });
      if (ex.obligors.every((o) => ex.confirmed[o])) {
        s.status = "HONORED";
        emit(tx, "HONORED", "both", { outcomeHash: computeOutcomeHash(s.outcome!, "HONORED") });
      }
      return;
    }

    case "CONTEST_EXECUTION": {
      requireStatus(s, "EXECUTION_PENDING");
      requireParty(s, cmd.actor);
      const ex = s.execution!;
      const obligor = other(cmd.actor);
      if (!ex.obligors.includes(obligor)) fail("INVALID_STATE", "the counterparty has no obligations to contest");
      if (ex.confirmed[obligor]) fail("INVALID_STATE", "already confirmed");
      if (ex.proofs[obligor] === null) fail("INVALID_STATE", "the counterparty has not submitted execution proof yet");
      ex.contested ??= { claimant: null, respondent: null };
      if (ex.contested[obligor] !== null) fail("ALREADY_SUBMITTED", "already contested");
      requireText(cmd.reason, 1, 1000, "reason");
      ex.contested[obligor] = { reason: cmd.reason, at: tx.now };
      emit(tx, "EXECUTION_CONTESTED", "both", { obligor, party: cmd.actor, reason: cmd.reason });
      return;
    }

    case "WITHDRAW": {
      const allowed: Status[] = ["AWAITING_RESPONDENT", "EVIDENCE", "ISSUE_CONFIRMATION", "BARGAINING"];
      if (!allowed.includes(s.status)) fail("INVALID_STATE", `cannot withdraw during ${s.status}`);
      requireParty(s, cmd.actor);
      emit(tx, "WITHDRAWN_BY", "both", { party: cmd.actor });
      unresolved(tx, "WITHDRAWN");
      return;
    }

    case "RECORD_NOTICE": {
      requireStatus(s, "AWAITING_RESPONDENT");
      if (cmd.actor !== "system") fail("NOT_AUTHORIZED", "notice delivery is recorded by the platform");
      validateNoticeDelivery(cmd.noticeDelivery);
      const prev = s.noticeDelivery;
      const incoming = structuredClone(cmd.noticeDelivery);
      if (prev && prev.delivered && prev.verifiedEndpoint && !(incoming.delivered && incoming.verifiedEndpoint)) {
        s.noticeDelivery = {
          ...prev,
          attempted: [...new Set([...prev.attempted, ...incoming.attempted])],
        };
      } else if (prev) {
        s.noticeDelivery = {
          ...incoming,
          attempted: [...new Set([...prev.attempted, ...incoming.attempted])],
        };
      } else {
        s.noticeDelivery = incoming;
      }
      emit(tx, "NOTICE_RECORDED", "both", {
        method: s.noticeDelivery.method,
        delivered: s.noticeDelivery.delivered,
        verifiedEndpoint: s.noticeDelivery.verifiedEndpoint,
        attempted: s.noticeDelivery.attempted,
      });
      return;
    }

    default: {
      const unknown: never = cmd;
      fail("INVALID_INPUT", `unknown command ${(unknown as { type: string }).type}`);
    }
  }
}

