function openIssueConfirmation(tx: Tx): void {
  const s = tx.state;
  s.status = "ISSUE_CONFIRMATION";
  s.stageDeadline = tx.now + s.config.stageTimeoutMs;
  emit(tx, "ISSUE_CONFIRMATION_OPENED", "both", { deadline: s.stageDeadline });
}

function startBargaining(tx: Tx): void {
  const s = tx.state;
  const wallClockDeadline = tx.now + s.config.bargainingWallClockMs;
  s.status = "BARGAINING";
  s.stageDeadline = null;
  s.bargaining = {
    round: 1,
    startedAt: tx.now,
    wallClockDeadline,
    roundDeadline: Math.min(tx.now + s.config.roundTimeoutMs, wallClockDeadline),
    submissions: { claimant: null, respondent: null },
    lastOffer: { claimant: null, respondent: null },
    private: { claimant: null, respondent: null },
    misses: { claimant: 0, respondent: 0 },
    gaps: [],
    proposal: null,
    history: [],
  };
  emit(tx, "ROUND_OPENED", "both", {
    round: 1,
    deadline: s.bargaining.roundDeadline,
    wallClockDeadline,
    maxRounds: s.config.maxRounds,
    proposalOpen: false,
  });
}

/**
 * Close the current round (both submitted, or deadline). Order of precedence:
 * accepted proposal → crossing offers → participation failure → stall → cap → next round.
 */
function resolveRound(tx: Tx): void {
  const s = tx.state;
  const b = s.bargaining!;
  const issues = s.issues!;
  const cfg = s.config;

  const submitted = { claimant: b.submissions.claimant !== null, respondent: b.submissions.respondent !== null };
  // M-10: Check mandate activity before mutating misses or emitting adverse TIMEOUT. If a platform outage
  // extended roundDeadline past a party's principal-signed mandate expiry, that party could not legally
  // submit; do not penalize them with a miss or TIMEOUT / MISSED_ROUNDS.
  const mandateActive = {
    claimant: s.parties.claimant.mandate.expiresAt > tx.now,
    respondent: s.parties.respondent!.mandate.expiresAt > tx.now,
  };
  const bothMandatesActive = mandateActive.claimant && mandateActive.respondent;
  for (const p of PARTIES) {
    const sub = b.submissions[p];
    if (sub !== null) b.lastOffer[p] = sub.offer;
    else if (mandateActive[p]) b.misses[p] += 1;
  }
  const responses = {
    claimant: b.submissions.claimant?.proposalResponse ?? (b.proposal ? "reject" : null),
    respondent: b.submissions.respondent?.proposalResponse ?? (b.proposal ? "reject" : null),
  } as const;
  const c = b.lastOffer.claimant;
  const r = b.lastOffer.respondent;
  const gap = c !== null && r !== null ? computeGap(issues, c, r) : null;

  b.history.push({
    round: b.round,
    submitted,
    offers: { claimant: c, respondent: r },
    proposal: b.proposal,
    responses,
    gap,
  });
  emit(tx, "ROUND_RECORD", "internal", { record: b.history[b.history.length - 1] });
  emit(tx, "ROUND_CLOSED", "both", { round: b.round });

  if (
    bothMandatesActive &&
    b.proposal !== null &&
    responses.claimant === "accept" &&
    responses.respondent === "accept" &&
    proposalSettles(b.proposal)
  ) {
    const terms = proposalTermsFor(b.proposal, "claimant");
    // Accepting already required each party's own mandate; this is defence in depth. A stand-in (no zone)
    // never settles: the round continues exactly as if the counterparty had rejected (CR2-2).
    if (withinMandate(issues, s.parties.claimant.mandate, terms) && withinMandate(issues, s.parties.respondent!.mandate, terms)) {
      settle(tx, "PROPOSAL_ACCEPTED", terms);
      return;
    }
  }
  if (!bothMandatesActive) {
    endWithoutDeal(tx, "NO_OVERLAP_AT_CAP");
    return;
  }
  if (c === null || r === null) {
    unresolved(tx, "TIMEOUT");
    return;
  }
  const privates = { claimant: b.private.claimant!, respondent: b.private.respondent! };
  const mandates = { claimant: s.parties.claimant.mandate, respondent: s.parties.respondent!.mandate };
  const mid = clampedCrossingTerms(issues, { claimant: c, respondent: r }, privates, mandates);
  if (bothMandatesActive && mid !== null && withinMandate(issues, mandates.claimant, mid) && withinMandate(issues, mandates.respondent, mid)) {
    settle(tx, "OVERLAP_MIDPOINT", mid);
    return;
  }
  if (b.misses.claimant >= 2 || b.misses.respondent >= 2) {
    unresolved(tx, "TIMEOUT");
    return;
  }
  b.gaps.push(gap!);
  if (isStalled(b.gaps, cfg.stallWindow, cfg.stallThreshold)) {
    endWithoutDeal(tx, "STALLED");
    return;
  }
  // MECH-4: never open a round with less than one full roundTimeoutMs window left on the bargaining wall clock,
  // or after either principal's mandate has expired (e.g. following an outage deadline extension).
  if (b.round >= cfg.maxRounds || b.wallClockDeadline - tx.now < cfg.roundTimeoutMs || !bothMandatesActive) {
    endWithoutDeal(tx, "NO_OVERLAP_AT_CAP");
    return;
  }

  b.round += 1;
  b.submissions = { claimant: null, respondent: null };
  b.proposal = null;
  if (b.round >= cfg.proposalFromRound) {
    // "offers" (research only, not in the public API: D35): each side's disagreement point is what it would get
    // by accepting the other side's current offer.
    const basis =
      cfg.proposalBasis === "offers"
        ? { claimant: { weights: privates.claimant.weights, walkaway: r }, respondent: { weights: privates.respondent.weights, walkaway: c } }
        : privates;
    const split = s.proposalKey ? proposalSplitFromKey(s.proposalKey, basis) : proposalSplit(s.audit.salt, s.id);
    // CR2-2 (option 1): always presented, zone or not, and never filtered by the (private) mandates, whose
    // effect would itself be a signal (Info-4). Mandates only gate acceptance (each party's own) and settlement.
    const p = presentProposal(issues, basis, split);
    b.proposal = { id: `${s.id}:r${b.round}`, round: b.round, views: p.views, settles: p.settles };
  }
  b.roundDeadline = Math.min(tx.now + cfg.roundTimeoutMs, b.wallClockDeadline);
  emit(tx, "ROUND_OPENED", "both", { round: b.round, deadline: b.roundDeadline, proposalOpen: b.proposal !== null });
  if (b.proposal) for (const p of PARTIES) emit(tx, "PROPOSAL_PRESENTED", p, { round: b.round, proposal: partyProposal(b.proposal, p) });
}

function endWithoutDeal(tx: Tx, reason: "STALLED" | "NO_OVERLAP_AT_CAP"): void {
  const s = tx.state;
  const detDeadline = tx.now + s.config.determinationTimeoutMs;
  const bothCanDetermine =
    s.parties.claimant.determinationConsent &&
    s.parties.respondent!.determinationConsent &&
    s.parties.claimant.mandate.expiresAt > detDeadline &&
    s.parties.respondent!.mandate.expiresAt > detDeadline;
  if (bothCanDetermine) {
    s.status = "DETERMINATION";
    s.determination = {
      startedAt: tx.now,
      deadline: detDeadline,
      triggeredBy: reason,
      finalOffers: { claimant: null, respondent: null },
      reference: null,
    };
    emit(tx, "DETERMINATION_OPENED", "both", { triggeredBy: reason, deadline: s.determination.deadline });
    return;
  }
  unresolved(tx, reason);
}

/**
 * Binding final-offer determination: the final offer closer to the reference
 * package wins outright. Missing final offers default to the last bargaining offer.
 */
function resolveDetermination(tx: Tx): void {
  const s = tx.state;
  const a = s.determination!;
  const b = s.bargaining!;
  const issues = s.issues!;
  for (const p of PARTIES) {
    if (a.finalOffers[p] === null) a.finalOffers[p] = structuredClone(b.lastOffer[p]);
  }
  if (a.reference === null) {
    unresolved(tx, "DETERMINATION_FAILED");
    return;
  }
  const pc = b.private.claimant;
  const pr = b.private.respondent;
  const meanWeights =
    pc && pr
      ? Object.fromEntries(issues.map((i) => [i.id, 0.5 * ((pc.weights[i.id] ?? 0) + (pr.weights[i.id] ?? 0))]))
      : null;
  const dc = meanWeights
    ? weightedDistance(issues, a.finalOffers.claimant!, a.reference, meanWeights)
    : distance(issues, a.finalOffers.claimant!, a.reference);
  const dr = meanWeights
    ? weightedDistance(issues, a.finalOffers.respondent!, a.reference, meanWeights)
    : distance(issues, a.finalOffers.respondent!, a.reference);
  let chosen: Party;
  if (Math.abs(dc - dr) <= EPS) {
    // Tie: unpredictable to the parties (salted) yet deterministic and replayable.
    // The "arbitration-tiebreak" tag is a frozen domain-separation constant (pre-D52 name): renaming it
    // would change which side wins a tie for the same salt, so it stays as is.
    const coin = parseInt(sha256Hex(`${s.audit.salt}:${s.id}:arbitration-tiebreak`).slice(0, 1), 16);
    chosen = coin % 2 === 0 ? "claimant" : "respondent";
  } else {
    chosen = dc < dr ? "claimant" : "respondent";
  }
  const winning = a.finalOffers[chosen]!;
  // MECH-1: the winning final offer must lie within BOTH parties' active signed determination mandates.
  const bothMandatesActive =
    s.parties.claimant.mandate.expiresAt > tx.now && s.parties.respondent!.mandate.expiresAt > tx.now;
  const withinBoth =
    bothMandatesActive &&
    withinDeterminationMandate(issues, s.parties.claimant.mandate, winning) &&
    withinDeterminationMandate(issues, s.parties.respondent!.mandate, winning);
  emit(tx, "DETERMINATION_DECISION", "internal", {
    finalOffers: a.finalOffers,
    reference: a.reference,
    distances: { claimant: dc, respondent: dr },
    chosen,
    withinBothMandates: withinBoth,
  });
  if (!withinBoth) {
    unresolved(tx, "DETERMINATION_FAILED");
    return;
  }
  settle(tx, "FINAL_OFFER_DETERMINATION", winning);
}

function computeObligors(issues: Issue[], terms: Package): Party[] {
  // MECH-2: an issue settled at the obligee's worst extreme (e.g. a refund of 0) requires no performance.
  const hasObligation = (issue: Issue): boolean => {
    const share = claimantShare(issue, terms[issue.id]!);
    const obligeeShare = issue.obligor === "respondent" ? share : 1 - share;
    return obligeeShare > EPS;
  };
  return PARTIES.filter((p) => issues.some((i) => i.obligor === p && hasObligation(i)));
}

function settle(tx: Tx, method: SettlementMethod, terms: Package): void {
  const s = tx.state;
  const issues = s.issues!;
  const obligors = computeObligors(issues, terms);
  s.outcome = {
    kind: "SETTLED",
    method,
    terms: structuredClone(terms),
    at: tx.now,
    roundsCompleted: s.bargaining?.history.length ?? 0,
  };
  const termsHash = computeTermsHash(s.outcome.terms);
  s.execution = {
    deadline: obligors.length === 0 ? tx.now : tx.now + s.config.executionTimeoutMs,
    obligors,
    proofs: { claimant: null, respondent: null },
    confirmed: { claimant: false, respondent: false },
    contested: { claimant: null, respondent: null },
  };
  s.stageDeadline = null;
  if (obligors.length === 0) {
    s.status = "HONORED";
    const outcomeHash = computeOutcomeHash(s.outcome, "HONORED");
    emit(tx, "SETTLED", "both", {
      method,
      terms: s.outcome.terms,
      obligors,
      executionDeadline: s.execution.deadline,
      termsHash,
      outcomeHash,
    });
    emit(tx, "HONORED", "both", { noObligations: true, outcomeHash });
    return;
  }
  s.status = "EXECUTION_PENDING";
  emit(tx, "SETTLED", "both", {
    method,
    terms: s.outcome.terms,
    obligors,
    executionDeadline: s.execution.deadline,
    termsHash,
    outcomeHash: computeOutcomeHash(s.outcome, "EXECUTION_PENDING"),
  });
  // MECH-10 / H-09: when multi-issue declared preferences leave Pareto-superior surplus above the settled package
  // on the full issue grid (checked post-hoc against both mandates and declared limits) using the dispute's secret
  // split α, offer it for optional mutual acceptance before execution.
  if (s.bargaining?.private.claimant && s.bargaining.private.respondent && s.parties.respondent) {
    const privates = { claimant: s.bargaining.private.claimant, respondent: s.bargaining.private.respondent };
    const split = s.proposalKey ? proposalSplitFromKey(s.proposalKey, privates) : proposalSplit(s.audit.salt, s.id);
    const improved = paretoImproveTerms(
      issues,
      s.outcome.terms,
      privates,
      { claimant: s.parties.claimant.mandate, respondent: s.parties.respondent.mandate },
      split,
    );
    if (improved !== null) {
      s.execution.improvement = {
        terms: improved,
        status: "OPEN",
        responses: { claimant: null, respondent: null },
      };
      emit(tx, "IMPROVEMENT_OFFERED", "both", { baselineTerms: s.outcome.terms, improvedTerms: improved });
    }
  }
}

function unresolved(tx: Tx, reason: ReasonCode): void {
  const s = tx.state;
  const roundsCompleted = s.bargaining?.history.length ?? 0;
  s.outcome = { kind: "UNRESOLVED", reason, at: tx.now, roundsCompleted };
  s.status = "UNRESOLVED";
  s.stageDeadline = null;
  emit(tx, "UNRESOLVED", "both", {
    reason,
    roundsCompleted,
    outcomeHash: computeOutcomeHash(s.outcome, "UNRESOLVED"),
  });
}

